const out = (file, mods) => {
  let s = "// Enums of the typescript API (data only). Generated by scripts/gen-enums.js.\n\n";
  const names = [];
  for (const [name, obj] of mods) {
    names.push(name);
    const entries = Object.entries(obj).filter(([k]) => isNaN(Number(k)));
    const numeric = entries.every(([, v]) => typeof v === "number");
    s += `export const ${name} = Object.freeze({\n`;
    for (const [k, v] of entries) s += `    ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`;
    if (numeric) for (const [k, v] of entries) if (obj[v] === k) s += `    ${JSON.stringify(String(v))}: ${JSON.stringify(k)},\n`;
    s += `});\n\n`;
  }
  return s;
};
const root = process.argv[2];
const t = await import(root + "/dist/ast/types.js");
const v = await import(root + "/dist/validation/parser/typedef.js");
const f = await import(root + "/dist/ast/features/type.js");
const st = await import(root + "/dist/ast/strings.js");
const n = await import(root + "/dist/node.js");
const fs = await import("node:fs");
const dst = process.argv[3];
fs.writeFileSync(dst + "/ast/types.js", out("", Object.entries(t)));
fs.writeFileSync(dst + "/validation/parser/typedef.js", out("", Object.entries(v)));
fs.writeFileSync(dst + "/ast/features/type.js", out("", [["FeatureWalkMode", f.FeatureWalkMode]]));
fs.writeFileSync(dst + "/enums-extra.js", out("", [["ResponseType", n.ResponseType], ["StringFlag", st.StringFlag], ["StringSource", st.StringSource]]));
console.log(Object.keys(t), Object.keys(v), n.version);

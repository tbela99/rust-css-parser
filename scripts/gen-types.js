// Copies the TypeScript declarations of the typescript library (its dist/index.d.ts, built by `npm run build` in the
// typescript project) to bindings/index.d.ts: the API of the bindings is the API of the typescript library, the
// declarations (types and TSDoc) are shared. build-bindings.sh copies them to the dist/ of each extension.
// usage: node scripts/gen-types.js <path to the typescript project>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.argv[2];

if (root == null) {
    console.error("usage: node scripts/gen-types.js <path to the typescript project>");
    process.exit(1);
}

const declarations = readFileSync(join(root, "dist", "index.d.ts"), "utf8");
const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version;
const header = `// Declarations of @tbela99/css-parser ${version}. Generated by scripts/gen-types.js: do not edit.\n\n`;

writeFileSync(new URL("../bindings/index.d.ts", import.meta.url), header + declarations);
console.log(`bindings/index.d.ts: @tbela99/css-parser ${version}`);

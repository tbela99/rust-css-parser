// Generates src/ast/types.rs from the TypeScript enums (src/ast/types.ts), so the values are identical.
// `Option::None` is spelled out: an enum may have a member named `None` (MergeRulesEnum).
// usage: node scripts/gen/enums.js <path to TS dist/ast/types.js> <path to TS src/ast/types.ts>
import { readFileSync } from "node:fs";
const [jsPath, tsPath] = process.argv.slice(2);
const mod = await import(jsPath);
const ts = readFileSync(tsPath, "utf8");
const types = { EnumAstNodeStatus: "u32", EnumToken: "u8", ColorType: "u8", ModuleCaseTransformEnum: "u32", ModuleScopeEnumOptions: "u32", WalkerOptionEnum: "u32", WalkerEvent: "u32", MergeRulesEnum: "u32" };
let out = "//! Port of `src/ast/types.ts`. Generated by `scripts/gen/enums.js`: do not edit.\n#![allow(non_upper_case_globals, non_snake_case, dead_code)]\n";
for (const [name, ty] of Object.entries(types)) {
  const e = mod[name];
  // member order of the declaration
  const body = ts.slice(ts.indexOf(`export enum ${name} {`));
  const decl = body.slice(0, body.indexOf("\n}"));
  const members = [...decl.matchAll(/^\s{4}([A-Za-z_][A-Za-z0-9_]*)\s*(=|,)/gm)].map((m) => m[1]);
  out += `\npub mod ${name} {\n`;
  for (const m of members) out += `    pub const ${m}: ${ty} = ${e[m]};\n`;
  out += `\n    /// member name of a value (first declared member), like \`${name}[value]\` in TypeScript\n    pub fn name(value: ${ty}) -> Option<&'static str> {\n        match value {\n`;
  const seen = new Set();
  for (const m of members) { const v = e[m]; if (e[v] === m && !seen.has(v)) { seen.add(v); out += `            ${v} => Some("${m}"),\n`; } }
  out += `            _ => Option::None,\n        }\n    }\n\n    /// value of a member name, like \`${name}[name]\` in TypeScript\n    pub fn value(name: &str) -> Option<${ty}> {\n        match name {\n`;
  for (const m of members) out += `            "${m}" => Some(${e[m]}),\n`;
  out += `            _ => Option::None,\n        }\n    }\n}\n`;
}
process.stdout.write(out);
